"""Generate user/libc/web/xml_xhtml_entities.h from Lexbor's named character references.

HTML Standard, "Parsing XML documents": the XHTML and MathML public identifiers it
lists all name one DTD, the entity declarations for the named character references.
The XML parser (user/libc/web/xml.c) reads that DTD, and no other external entity.
The names and values come from the vendored HTML tokenizer table
(third_party/lexbor/source/lexbor/html/tokenizer/res.h), so the browser's HTML and
XML parsers decode the same references. Only the forms with a semicolon are XML
names; the five entities XML predefines are left to the XML parser.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
source = root / "third_party/lexbor/source/lexbor/html/tokenizer/res.h"
target = root / "user/libc/web/xml_xhtml_entities.h"

text = source.read_text(encoding="utf-8")
body = text[text.index("lxb_html_tokenizer_res_entities_sbst[] ="):]
body = body[body.index("{") + 1:body.index("};")]
entry = re.compile(r'\{(0x[0-9a-f]+),\s*(NULL|"((?:[^"\\]|\\.)*)"),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\}')
def c_bytes(literal):
    """A C string literal's bytes: \\xH.. (one or more hex digits), \\ooo and \\c escapes."""
    out, i = bytearray(), 0
    simple = {"n": 10, "t": 9, "r": 13, "\\": 92, '"': 34, "'": 39, "0": 0}
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(ord(c)); i += 1; continue
        c = literal[i + 1]
        if c == "x":
            j = i + 2
            while j < len(literal) and literal[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(int(literal[i + 2:j], 16) & 0xFF); i = j
        elif c in "01234567":
            j = i + 1
            while j < i + 4 and j < len(literal) and literal[j] in "01234567":
                j += 1
            out.append(int(literal[i + 1:j], 8) & 0xFF); i = j
        else:
            out.append(simple[c]); i += 2
    return bytes(out)
table = []
for match in entry.finditer(body):
    value = None
    if match.group(2) != "NULL":
        value = c_bytes(match.group(3))
        if len(value) != int(match.group(4)):
            raise SystemExit("value length mismatch")
    table.append((int(match.group(1), 16), value, int(match.group(5)), int(match.group(6)), int(match.group(7))))
if not table:
    raise SystemExit("entity table not found")

names = {}
stack = [(1, b"")]  # explicit stack: no recursion over the tree depth
while stack:
    index, prefix = stack.pop()
    if not index:
        continue
    key, value, left, right, after = table[index]
    name = prefix + bytes([key])
    if value is not None and name.endswith(b";"):
        names[name[:-1].decode("ascii")] = value.decode("utf-8")
    stack.extend(((left, prefix), (right, prefix), (after, name)))

predefined = {"lt", "gt", "amp", "quot", "apos"}
lines = []
for name in sorted(names):
    if name in predefined:
        continue
    refs = "".join("&#x%X;" % ord(c) for c in names[name])
    lines.append('<!ENTITY %s "%s">\n' % (name, refs))
if len(lines) < 2000:
    raise SystemExit("unexpectedly few entities: %d" % len(lines))

out = ["/* Generated by scripts/xml_xhtml_entities.py from third_party/lexbor/source/lexbor/html/tokenizer/res.h.",
       "   The DTD of the HTML Standard's XHTML and MathML public identifiers (%d entities). */" % len(lines),
       "static const char xml_xhtml_entities_dtd[] ="]
chunk = ""
for line in lines:
    if len(chunk) + len(line) > 96:
        out.append('    "%s"' % chunk.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n"))
        chunk = ""
    chunk += line
if chunk:
    out.append('    "%s"' % chunk.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n"))
out[-1] += ";"
target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("wrote", target.relative_to(root), len(lines), "entities")
