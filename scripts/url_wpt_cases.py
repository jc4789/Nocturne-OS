#!/usr/bin/env python3
"""Generate tests/js_url_wpt_cases.js from a WPT checkout's url/resources.

The URL parsing, setter and IDNA data are copied unchanged (WPT, BSD 3-Clause);
the runner checks the browser's URL against them as url-constructor,
url-origin, url-statics-*, url-setters and toascii do.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

FILES = {"urltestdata": "urltestdata.json", "javascriptOnly": "urltestdata-javascript-only.json",
         "setters": "setters_tests.json", "toascii": "toascii.json"}

RUNNER = r"""
function runURLWPTCases() {
    const failures = [];
    let total = 0;
    const fail = (name, message) => { failures.push(name + ': ' + message); };
    const same = (name, what, actual, expected) => {
        if (actual !== expected) fail(name, what + ' ' + JSON.stringify(actual) + ' !== ' + JSON.stringify(expected));
    };
    const parts = ['href', 'protocol', 'username', 'password', 'host', 'hostname', 'port', 'pathname', 'search', 'hash'];
    for (const test of [...URL_WPT.urltestdata, ...URL_WPT.javascriptOnly]) {
        if (typeof test === 'string') continue;
        total++;
        const base = test.base === null ? undefined : test.base;
        const name = 'parse ' + JSON.stringify(test.input) + (base === undefined ? '' : ' against ' + JSON.stringify(base));
        same(name, 'canParse', URL.canParse(test.input, base), !test.failure);
        same(name, 'parse', URL.parse(test.input, base) === null, !!test.failure);
        let url;
        try { url = new URL(test.input, base); }
        catch (e) { if (!test.failure || !(e instanceof TypeError)) fail(name, String(e)); continue; }
        if (test.failure) { fail(name, 'parsed as ' + url.href); continue; }
        for (const part of parts) same(name, part, url[part], test[part]);
        if ('origin' in test) same(name, 'origin', url.origin, test.origin);
        if ('searchParams' in test) same(name, 'searchParams', url.searchParams.toString(), test.searchParams);
    }
    for (const attribute of Object.keys(URL_WPT.setters)) {
        if (attribute === 'comment') continue;
        for (const test of URL_WPT.setters[attribute]) {
            total++;
            const name = 'set ' + attribute + ' of ' + JSON.stringify(test.href) + ' to ' + JSON.stringify(test.new_value);
            try {
                const url = new URL(test.href);
                url[attribute] = test.new_value;
                for (const part of Object.keys(test.expected)) same(name, part, url[part], test.expected[part]);
            } catch (e) { fail(name, String(e)); }
        }
    }
    for (const test of URL_WPT.toascii) {
        if (typeof test === 'string') continue;
        total++;
        const name = 'host ' + JSON.stringify(test.input);
        try {
            if (test.output === null) {
                let parsed = false;
                try { new URL('https://' + test.input + '/x'); parsed = true; } catch (e) { if (!(e instanceof TypeError)) throw e; }
                if (parsed) fail(name, 'parsed');
            } else {
                const url = new URL('https://' + test.input + '/x');
                same(name, 'host', url.host, test.output);
                same(name, 'hostname', url.hostname, test.output);
                same(name, 'pathname', url.pathname, '/x');
                same(name, 'href', url.href, 'https://' + test.output + '/x');
            }
            for (const attribute of ['host', 'hostname']) {
                const url = new URL('https://x/x');
                url[attribute] = test.input;
                same(name + ' by ' + attribute, attribute, url[attribute], test.output === null ? 'x' : test.output);
            }
        } catch (e) { fail(name, String(e)); }
    }
    return {total, failures};
}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("wpt", type=Path, help="the WPT checkout")
    ap.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "tests" / "js_url_wpt_cases.js")
    a = ap.parse_args()
    resources = a.wpt / "url" / "resources"
    revision = subprocess.run(["git", "-C", str(a.wpt), "rev-parse", "HEAD"], check=True,
                              capture_output=True, text=True).stdout.strip()
    data, sources = {}, []
    for key, name in FILES.items():
        raw = (resources / name).read_bytes()
        data[key] = json.loads(raw)
        sources.append(f" * url/resources/{name} sha256 {hashlib.sha256(raw).hexdigest()}")
    # '<' escaped: the data sits inside an inline HTML script.
    literal = json.dumps(data, ensure_ascii=True, separators=(",", ":")).replace("<", "\\u003c")
    text = "\n".join([f"/* Generated by scripts/url_wpt_cases.py from web-platform-tests {revision}",
                      " * (BSD 3-Clause, https://github.com/web-platform-tests/wpt); data unchanged.",
                      *sources, " */",
                      "const URL_WPT = " + literal + ";"]) + RUNNER
    a.output.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
