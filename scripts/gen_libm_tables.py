#!/usr/bin/env python3
"""Generates user/libc/math_tables.h, the constants and tables of user/libc/math.c.

Everything is derived from first principles with mpmath at 700 decimal digits:
  * polynomial coefficients are Chebyshev-node interpolants of the Taylor-series
    functions below (near-minimax; the maximum error of each fit is printed),
  * 2^(j/64), log(1 + i/128), 1/(1 + i/128) and atan(i/8) as double+double pairs,
  * the bits of 2/pi (Payne-Hanek) and pi/2 in 32-bit chunks (Cody-Waite).
Usage: gen_libm_tables.py [output.h]   (default: user/libc/math_tables.h)
"""
import os
import sys
from mpmath import mp, mpf, matrix, lu_solve, cos, pi, log, atan, floor, factorial, nstr, frexp, ldexp

mp.dps = 700
out = []


def emit(s=""):
    out.append(s)


def hx(d):
    return d.hex()


def hi_lo(x):
    h = float(x)
    return h, float(x - mpf(h))


def trunc_bits(x, nbits):
    m, e = frexp(x)
    m = floor(m * (mpf(2) ** nbits)) / (mpf(2) ** nbits)
    return ldexp(m, e)


def cheb_fit(g, a, b, deg):
    n = deg + 1
    a, b = mpf(a), mpf(b)
    xs = [(a + b) / 2 + (b - a) / 2 * cos(pi * (2 * k + 1) / (2 * n)) for k in range(n)]
    A = matrix(n, n)
    for i, x in enumerate(xs):
        for j in range(n):
            A[i, j] = x ** j
    c = lu_solve(A, matrix([g(x) for x in xs]))
    return [c[i] for i in range(n)]


def evalp(c, x):
    r = mpf(0)
    for k in reversed(c):
        r = r * x + k
    return r


def report(name, g, c, a, b):
    cd = [mpf(float(ci)) for ci in c]
    m = mpf(0)
    n = 2000
    for i in range(n + 1):
        x = mpf(a) + (mpf(b) - mpf(a)) * i / n
        m = max(m, abs(evalp(cd, x) - g(x)))
    sys.stderr.write("%-6s max abs error %s (2^%.1f)\n" % (name, nstr(m, 4), float(log(m, 2))))


def poly(name, g, a, b, deg):
    c = cheb_fit(g, a, b, deg)
    report(name, g, c, a, b)
    emit("static const double %s[%d] = {" % (name, len(c)))
    emit("    " + ", ".join(hx(float(ci)) for ci in c))
    emit("};")


def series(coef, x, n=60):
    return sum(coef(k) * x ** k for k in range(n))


def define(name, v):
    emit("#define %s %s" % (name, hx(float(v))))


emit("/* Generated by scripts/gen_libm_tables.py - do not edit by hand. */")
# sin(r) = r + r^3 S(r^2), S(z) = sum_{n>=1} (-1)^n z^(n-1)/(2n+1)!
poly("sin_c", lambda z: series(lambda k: (-1) ** (k + 1) / factorial(2 * k + 3), z), 0, 0.64, 7)
# cos(r) = 1 - r^2/2 + r^4 C(r^2), C(z) = sum_{n>=2} (-1)^n z^(n-2)/(2n)!
poly("cos_c", lambda z: series(lambda k: (-1) ** k / factorial(2 * k + 4), z), 0, 0.64, 5)
# exp(r) = 1 + r + r^2 E(r), E(r) = sum_{n>=2} r^(n-2)/n!
expm1_series = lambda r: series(lambda k: 1 / factorial(k + 2), r)
poly("exp_c", expm1_series, -mpf("0.0056"), mpf("0.0056"), 4)
poly("expm1_c", expm1_series, -mpf("0.35"), mpf("0.35"), 11)
# log(1+r) = r - r^2/2 + r^3 R(r), R(r) = sum_{n>=3} (-1)^(n+1) r^(n-3)/n
poly("log_c", lambda r: series(lambda k: (-1) ** k / (k + 3), r, 200), -mpf("0.0079"), mpf("0.0079"), 7)
# atan(t) = t + t^3 Q(t^2), Q(s) = sum_{n>=1} (-1)^n s^(n-1)/(2n+1)
poly("atan_c", lambda s: series(lambda k: (-1) ** (k + 1) / (2 * k + 3), s, 100), 0, mpf("0.0042"), 5)

# pi/2 in 32-bit chunks (a count below 2^21 times a chunk is exact) plus a double tail
P = pi / 2
P1 = floor(P * 2 ** 31) / mpf(2) ** 31
r1 = P - P1
P2 = floor(r1 * 2 ** 63) / mpf(2) ** 63
r2 = r1 - P2
P3 = floor(r2 * 2 ** 95) / mpf(2) ** 95
r3 = r2 - P3
define("PIO2_1", P1)
define("PIO2_2", P2)
define("PIO2_3", P3)
define("PIO2_4", r3)
define("INV_PIO2", 2 / pi)
h, l = hi_lo(P)
define("PIO2_HI", h)
define("PIO2_LO", l)
h, l = hi_lo(pi)
define("PI_HI", h)
define("PI_LO", l)
define("PI3_4_HI", 3 * pi / 4)
ln2 = log(2)
h = trunc_bits(ln2, 42)  # e * LN2_HI is exact for |e| < 2^11
define("LN2_HI", h)
define("LN2_LO", ln2 - h)
h = trunc_bits(ln2 / 64, 36)  # k * LN2N_HI is exact for |k| < 2^17
define("LN2N_HI", h)
define("LN2N_LO", ln2 / 64 - h)
define("INV_LN2N", 64 / ln2)
define("INV_LN2", 1 / ln2)
h, l = hi_lo(1 / ln2)
define("LOG2E_HI", h)
define("LOG2E_LO", l)
h, l = hi_lo(1 / log(10))
define("LOG10E_HI", h)
define("LOG10E_LO", l)

emit("/* 2^(j/64) as high, low */")
emit("static const double exp_tab[128] = {")
for j in range(64):
    h, l = hi_lo(mpf(2) ** (mpf(j) / 64))
    emit("    %s, %s," % (hx(h), hx(l)))
emit("};")
emit("/* per i: 1/(1+i/128) as high, low; log(1+i/128) as high, low */")
emit("static const double log_tab[128][4] = {")
for i in range(128):
    mi = 1 + mpf(i) / 128
    ch, cl = hi_lo(1 / mi)
    lh, ll = hi_lo(log(mi))
    emit("    {%s, %s, %s, %s}," % (hx(ch), hx(cl), hx(lh), hx(ll)))
emit("};")
emit("/* atan(i/8) as high, low */")
emit("static const double atan_tab[9][2] = {")
for i in range(9):
    h, l = hi_lo(atan(mpf(i) / 8))
    emit("    {%s, %s}," % (hx(h), hx(l)))
emit("};")
emit("/* 2/pi, most significant word first: word w holds fraction bits 64w+1 .. 64w+64 */")
emit("static const uint64_t two_over_pi[20] = {")
f = 2 / pi
words = []
for _ in range(20):
    f *= 2 ** 64
    w = int(floor(f))
    words.append("0x%016xULL" % w)
    f -= w
emit("    " + ", ".join(words))
emit("};")

path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "user", "libc", "math_tables.h")
with open(path, "w", newline="\n") as fh:
    fh.write("\n".join(out) + "\n")
