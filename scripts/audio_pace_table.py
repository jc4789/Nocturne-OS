#!/usr/bin/env python3
"""kernel/src/dev/audio_pace.h を書く：音の混ぜ場が比を変えるときの補間の係数。

Kaiser 窓の sinc。8 タップ、一サンプルを 64 に分けた 65 行、Q15。各行の和は 32768。
行 0 は 4 番目のタップだけ、行 64 は 5 番目のタップだけで、比が 1 なら音はそのまま通る。
"""
import math

TAPS, PHASES, BETA = 8, 64, 5.0


def bessel_i0(x):
    total = term = 1.0
    k = 1
    while term > 1e-12 * total:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def tap(x):
    """中心から x サンプルの係数。窓は ±TAPS/2 で 0。"""
    r = x / (TAPS / 2)
    if abs(r) >= 1:
        return 0.0
    sinc = 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)
    return sinc * bessel_i0(BETA * math.sqrt(1 - r * r)) / bessel_i0(BETA)


rows = []
for phase in range(PHASES + 1):
    fraction = phase / PHASES
    raw = [tap(m - (TAPS / 2 - 1) - fraction) for m in range(TAPS)]
    scale = 32768 / sum(raw)
    row = [round(v * scale) for v in raw]
    row[row.index(max(row))] += 32768 - sum(row)
    rows.append(row)

with open('kernel/src/dev/audio_pace.h', 'w', encoding='utf8', newline='\n') as out:
    out.write('/* Generated by scripts/audio_pace_table.py. Do not edit. */\n')
    out.write('#pragma once\n#include <stdint.h>\n')
    out.write(f'#define PACE_TAPS {TAPS}\n#define PACE_PHASE_BITS {int(math.log2(PHASES))}\n')
    out.write(f'static const int32_t pace_filter[{PHASES + 1}][{TAPS}] = {{\n')
    for row in rows:
        out.write('    {' + ', '.join(str(v) for v in row) + '},\n')
    out.write('};\n')
