"""The store's case-folding table (kernel/src/fs/fold_table.h) from Python's Unicode database.

Simple case folding (CaseFolding.txt statuses C and S) maps one code point to one. Python exposes
full folding (C and F) as str.casefold; where that gives one code point it is the C mapping, and
where it gives several the S mapping, when there is one, is the lowercase letter (U+1E9E to U+00DF,
the title-case Greek letters to their lowercase forms), and otherwise the code point folds to
itself (U+0130 has only a Turkic mapping). A volume keeps the table it was made with
(common/store_format.h), so a later Unicode version changes nothing on volumes made before it.

    python scripts/gen_fold.py           write the table
    python scripts/gen_fold.py --check   fail when the table is not what this Python makes
"""
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "kernel/src/fs/fold_table.h"


def simple_fold(cp):
    c = chr(cp)
    full = c.casefold()
    if len(full) == 1:
        return ord(full)
    lower = c.lower()
    if len(lower) == 1 and lower.casefold() == full:
        return ord(lower)
    return cp


def generate():
    pairs = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        to = simple_fold(cp)
        if to != cp:
            pairs.append((cp, to))
    major, minor, update = (int(x) for x in unicodedata.unidata_version.split("."))
    lines = [
        f"/* Generated by scripts/gen_fold.py from Unicode {unicodedata.unidata_version}: do not edit. */",
        "/* Simple case folding: every code point that folds to another, sorted (fs/names.c). */",
        f"#define FOLD_UNICODE 0x{major:02x}{minor:02x}{update:02x}u",
        f"#define FOLD_PAIRS {len(pairs)}u",
        "static const uint32_t fold_pairs[FOLD_PAIRS][2] = {",
    ]
    for i in range(0, len(pairs), 6):
        lines.append("    " + " ".join(f"{{0x{a:x}, 0x{b:x}}}," for a, b in pairs[i:i + 6]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUTPUT} differs from Unicode {unicodedata.unidata_version}")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
