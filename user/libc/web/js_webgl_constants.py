"""Generate the WebGL constant tables from the Khronos GLES headers vendored
with Mesa. WebGL 1 exposes the OpenGL ES 2.0 enumerants and WebGL 2 adds the
OpenGL ES 3.0 ones, each minus the names the WebGL IDL leaves out (client
state queries, buffer mapping, program binaries, ETC compression)."""
import re
from pathlib import Path

base = Path(__file__).resolve().parent
include = base.parents[2] / 'third_party' / 'mesa' / 'include'

WEBGL1_OMIT = {
    'ES_VERSION_2_0', 'FALSE', 'TRUE', 'FIXED', 'SHADER_COMPILER', 'SHADER_BINARY_FORMATS',
    'NUM_SHADER_BINARY_FORMATS', 'NUM_COMPRESSED_TEXTURE_FORMATS', 'INFO_LOG_LENGTH', 'SHADER_SOURCE_LENGTH',
    'ACTIVE_UNIFORM_MAX_LENGTH', 'ACTIVE_ATTRIBUTE_MAX_LENGTH', 'EXTENSIONS',
}
WEBGL1_EXTRA = [
    ('DEPTH_STENCIL', 0x84F9), ('DEPTH_STENCIL_ATTACHMENT', 0x821A), ('UNPACK_FLIP_Y_WEBGL', 0x9240),
    ('UNPACK_PREMULTIPLY_ALPHA_WEBGL', 0x9241), ('CONTEXT_LOST_WEBGL', 0x9242),
    ('UNPACK_COLORSPACE_CONVERSION_WEBGL', 0x9243), ('BROWSER_DEFAULT_WEBGL', 0x9244),
]
WEBGL2_OMIT = {
    'ES_VERSION_3_0', 'MAP_READ_BIT', 'MAP_WRITE_BIT', 'MAP_INVALIDATE_RANGE_BIT', 'MAP_INVALIDATE_BUFFER_BIT',
    'MAP_FLUSH_EXPLICIT_BIT', 'MAP_UNSYNCHRONIZED_BIT', 'BUFFER_ACCESS_FLAGS', 'BUFFER_MAPPED',
    'BUFFER_MAP_POINTER', 'BUFFER_MAP_LENGTH', 'BUFFER_MAP_OFFSET', 'PROGRAM_BINARY_RETRIEVABLE_HINT',
    'PROGRAM_BINARY_LENGTH', 'NUM_PROGRAM_BINARY_FORMATS', 'PROGRAM_BINARY_FORMATS',
    'PRIMITIVE_RESTART_FIXED_INDEX', 'NUM_EXTENSIONS', 'MAJOR_VERSION', 'MINOR_VERSION',
    'ACTIVE_UNIFORM_BLOCK_MAX_NAME_LENGTH', 'TRANSFORM_FEEDBACK_VARYING_MAX_LENGTH', 'UNIFORM_NAME_LENGTH',
    'UNIFORM_BLOCK_NAME_LENGTH',
}
WEBGL2_EXTRA = [('MAX_CLIENT_WAIT_TIMEOUT_WEBGL', 0x9247)]


def section(path, version):
    text = path.read_text(encoding='utf-8')
    start = text.index(f'#ifndef GL_{version}\n')
    end = text.index(f'#endif /* GL_{version} */', start)
    out = []
    for name, value in re.findall(r'^#define GL_(\w+)\s+(\S+)\s*$', text[start:end], re.M):
        number = int(re.sub(r'(?i)u?l*$', '', value), 0)
        out.append((name, number))
    return out


def keep(name, omit):
    return name not in omit and not (name.startswith('COMPRESSED_') and ('_EAC' in name or '_ETC2' in name))


def table(name, items):
    lines = [f'static const struct webgl_constant {name}[] = {{']
    for key, value in items:
        if value == 0xFFFFFFFFFFFFFFFF:  # TIMEOUT_IGNORED is a GLint64 -1 in WebGL
            literal = '-1.0'
        else:
            literal = f'{value}.0'
        lines.append(f'    {{"{key}", {literal}}},')
    lines.append('};')
    return '\n'.join(lines)


webgl1 = [(n, v) for n, v in section(include / 'GLES2' / 'gl2.h', 'ES_VERSION_2_0') if keep(n, WEBGL1_OMIT)]
webgl1 += WEBGL1_EXTRA
known = {n for n, _ in webgl1}
webgl2 = [(n, v) for n, v in section(include / 'GLES3' / 'gl3.h', 'ES_VERSION_3_0')
          if keep(n, WEBGL2_OMIT) and n not in known]
webgl2 += WEBGL2_EXTRA
output = '/* Generated by js_webgl_constants.py from the vendored Khronos GLES headers. */\n'
output += table('webgl1_constants', webgl1) + '\n' + table('webgl2_constants', webgl2) + '\n'
target = base / 'js_webgl_constants.inc'
if not target.exists() or target.read_text(encoding='utf-8') != output:
    target.write_text(output, encoding='utf-8', newline='\n')
