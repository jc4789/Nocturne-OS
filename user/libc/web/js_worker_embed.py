"""Embed private dedicated-worker bootstrap separately from DOM/window."""
import json
import re
import hashlib
from pathlib import Path
base = Path(__file__).resolve().parent
source = (base / 'js_worker_runtime.js').read_text(encoding='utf-8')
source = re.sub(r'/\* @include ([a-z_]+\.js) \*/',lambda m:(base / m[1]).read_text(encoding='utf-8'),source)
# The exact same pinned, MIT upstream module used by the Window generator.
# Only its final export is adapted to this private Worker closure.
streams = base.parents[2] / 'third_party/web_streams'
manifest = json.loads((streams / 'upstream.json').read_text(encoding='utf-8'))
ponyfill = (streams / 'ponyfill.mjs').read_bytes()
if hashlib.sha256(ponyfill).hexdigest() != manifest['files']['ponyfill.mjs']:
    raise ValueError('Streams upstream hash mismatch')
module, count = re.subn(r'export\{([A-Za-z,]+)\};\s*$', r'return {\1};', ponyfill.decode('utf-8'))
if count != 1 or source.count('/* @streams-ponyfill */') != 1:
    raise ValueError('Worker Streams export/include contract changed')
source = source.replace('/* @streams-ponyfill */', module)
output = '/* Generated by js_worker_embed.py; no DOM bootstrap. */\nstatic const char js_worker_runtime[] =\n'
output += '\n'.join(json.dumps(line,ensure_ascii=True).replace('?',r'\?') for line in source.splitlines(keepends=True))+';\n'
(base / 'js_worker_runtime.inc').write_text(output,encoding='utf-8',newline='\n')
