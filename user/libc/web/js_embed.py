"""Generate the checked-in C string used by the freestanding browser host."""
import json
import re
import hashlib
from pathlib import Path

base = Path(__file__).resolve().parent
def expand(name):
    return re.sub(r'/\* @include ([a-z_]+\.js) \*/',
                  lambda m: (base / m[1]).read_text(encoding="utf-8"), (base / name).read_text(encoding="utf-8"))
def c_string(name, text):
    return ("static const char " + name + "[] =\n" +
            "\n".join(json.dumps(line, ensure_ascii=True).replace('?', r'\?') for line in text.splitlines(keepends=True)) +
            ";\n")
source = expand("js_bootstrap.js")
# Preserve the upstream module verbatim on disk. Only its export declaration
# becomes a return inside the host-private bootstrap scope, never a page module.
streams = base.parents[2] / "third_party/web_streams"
manifest = json.loads((streams / "upstream.json").read_text(encoding="utf-8"))
ponyfill = (streams / "ponyfill.mjs").read_bytes()
if hashlib.sha256(ponyfill).hexdigest() != manifest["files"]["ponyfill.mjs"]:
    raise ValueError("Streams upstream hash mismatch")
module = ponyfill.decode("utf-8")
module, count = re.subn(r'export\{([A-Za-z,]+)\};\s*$', r'return {\1};', module)
if count != 1 or source.count("/* @streams-ponyfill */") != 1:
    raise ValueError("Streams export/include contract changed")
source = source.replace("/* @streams-ponyfill */", module)
# The editing program wraps the execCommand draft's implementation, kept as it
# came in third_party/editing apart from the changes its README lists; the
# manifest's hash of the file in use catches an edit the README does not list.
editing_dir = base.parents[2] / "third_party/editing"
editing_manifest = json.loads((editing_dir / "upstream.json").read_text(encoding="utf-8"))
implementation = (editing_dir / "implementation.js").read_bytes()
if hashlib.sha256(implementation).hexdigest() != editing_manifest["files"]["implementation.js"]["local"]:
    raise ValueError("Editing implementation hash mismatch: update third_party/editing/README.md and upstream.json")
editing = expand("js_editing.js")
if editing.count("/* @editing-implementation */") != 1:
    raise ValueError("Editing implementation include contract changed")
editing = editing.replace("/* @editing-implementation */", implementation.decode("utf-8"))
# The locale, Web Audio and editing programs are compiled apart: a realm runs
# each when it first needs Intl, first touches a Web Audio interface, or first
# needs an editing command.
output = "/* Generated by js_embed.py from js_bootstrap.js, js_locale.js, js_webaudio.js and js_editing.js. */\n"
output += c_string("js_bootstrap", source) + c_string("js_locale", expand("js_locale.js"))
output += c_string("js_webaudio", expand("js_webaudio.js"))
output += c_string("js_editing", editing)
(base / "js_bootstrap.inc").write_text(output, encoding="utf-8", newline="\n")
