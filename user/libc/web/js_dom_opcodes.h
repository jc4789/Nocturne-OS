static int dom_opcode(const char *name) {
    int lo=0,hi=DOM_OPCODE_COUNT;
    while(lo<hi){int mid=(lo+hi)/2,c=strcmp(name,dom_opcode_names[mid]);if(!c)return mid;if(c<0)hi=mid;else lo=mid+1;}
    return -1;
}
