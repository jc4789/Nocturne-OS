/* Scan code set 1, the form the VM's hosts (Hyper-V's keyboard, RDP's input) say a key in, to the HID
   usage the input layer takes. Only for vm/: real keyboards report usages themselves. */
#pragma once
#include <stdint.h>
#include <stdbool.h>

static const uint8_t set1_plain[128] = {
    [0x01] = 0x29, 0x1E, 0x1F, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x2D, 0x2E, 0x2A, 0x2B,
    [0x10] = 0x14, 0x1A, 0x08, 0x15, 0x17, 0x1C, 0x18, 0x0C, 0x12, 0x13, 0x2F, 0x30, 0x28, 0xE0, 0x04, 0x16,
    [0x20] = 0x07, 0x09, 0x0A, 0x0B, 0x0D, 0x0E, 0x0F, 0x33, 0x34, 0x35, 0xE1, 0x31, 0x1D, 0x1B, 0x06, 0x19,
    [0x30] = 0x05, 0x11, 0x10, 0x36, 0x37, 0x38, 0xE5, 0x55, 0xE2, 0x2C, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E,
    [0x40] = 0x3F, 0x40, 0x41, 0x42, 0x43, 0x53, 0x47, 0x5F, 0x60, 0x61, 0x56, 0x5C, 0x5D, 0x5E, 0x57, 0x59,
    [0x50] = 0x5A, 0x5B, 0x62, 0x63,
    [0x56] = 0x64, 0x44, 0x45,
    [0x70] = 0x88, [0x73] = 0x87, [0x79] = 0x8A, [0x7B] = 0x8B, [0x7D] = 0x89,
};
static const uint8_t set1_extended[128] = {
    [0x1C] = 0x58, [0x1D] = 0xE4, [0x35] = 0x54, [0x37] = 0x46, [0x38] = 0xE6,
    [0x47] = 0x4A, [0x48] = 0x52, [0x49] = 0x4B, [0x4B] = 0x50, [0x4D] = 0x4F,
    [0x4F] = 0x4D, [0x50] = 0x51, [0x51] = 0x4E, [0x52] = 0x49, [0x53] = 0x4C,
    [0x5B] = 0xE3, [0x5C] = 0xE7, [0x5D] = 0x65,
};

/* The usage of a key's code (without its release bit); 0 for what is no key (0xE0 0x2A, a print screen's fake shift). */
static inline uint16_t set1_usage(uint8_t code, bool extended) {
    return (extended ? set1_extended : set1_plain)[code & 0x7F];
}
